#!/usr/bin/env python3
"""Map script callers without executing scripts, importing models or reading secrets."""
import argparse
import ast
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
TEXT = {'.py', '.mjs', '.js', '.ts', '.tsx', '.sh', '.md', '.json', '.yml', '.yaml', '.txt', '.swift', '.pbxproj'}


def area(name):
    if any(word in name for word in ('singing', 'singer', 'sung', 'spleeter', 'vocal_identity')):
        return 'Singing and vocal research'
    if any(word in name for word in ('trial', 'cloud_', 'runpod', 'vast_')):
        return 'Cloud qualification and budgets'
    if any(word in name for word in ('dj_', 'club_', 'afro_', 'groove', 'electronic')):
        return 'DJ and arrangement research'
    if any(word in name for word in ('dna', 'taste', 'playlist')):
        return 'Music DNA'
    if any(word in name for word in ('web_', 'ios_', 'offline', 'studio_', 'bundle', 'release')):
        return 'Build, packaging and local servers'
    return 'Core audio, fixtures and evaluation'


def inventory():
    tracked = sorted(set(subprocess.check_output(['git', 'ls-files', '-z', '--cached', '--others', '--exclude-standard'], cwd=ROOT).decode().split('\0')))
    # Include newly authored local script files, without indexing ignored captures/models.
    scripts = sorted(p for p in (ROOT/'scripts').iterdir() if p.suffix in {'.py', '.mjs', '.sh'} and p.is_file())
    sources = {}
    for name in tracked:
        path = ROOT/name
        if not name or path.suffix not in TEXT or name.startswith('docs/evidence/') or path.is_symlink() or not path.is_file():
            continue
        if name in {'scripts/README.md', 'docs/REPOSITORY_LAYOUT.md'} or path.stat().st_size > 2*1024**2:
            continue
        sources[name] = path.read_text(errors='replace')
    rows = []
    for script in scripts:
        calls, history = [], []
        filename = re.compile(r'(?<![\w.-])' + re.escape(script.name) + r'(?![\w.-])')
        module = re.compile(r'(?m)^\s*(?:from\s+' + re.escape(script.stem) + r'\s+import|import\s+' + re.escape(script.stem) + r'\b)')
        for name, text in sources.items():
            if name == str(script.relative_to(ROOT)):
                continue
            if script.name not in text and (script.suffix != '.py' or script.stem not in text):
                continue
            for number, line in enumerate(text.splitlines(), 1):
                if filename.search(line) or script.suffix == '.py' and module.search(line):
                    (history if name.startswith('docs/') or name.endswith('.md') else calls).append(f'{name}:{number}')
        purpose = ''
        if script.suffix == '.py':
            purpose = (ast.get_docstring(ast.parse(script.read_text())) or '').split('\n')[0]
        rows.append({'path': str(script.relative_to(ROOT)), 'area': area(script.name),
                     'purpose': purpose, 'code_callers': calls, 'documented_references': history})
    return {'scope': 'Static literal and Python import references; dynamic paths require caller review before moving.',
            'scripts': rows, 'count': len(rows)}


def index(report):
    lines = ['# Script directory', '',
             'Generated by `python3 scripts/audit_repository.py --index`. These are stable command/import paths;',
             'a listing is not permission to run a paid trial. See [layout and ownership](../docs/REPOSITORY_LAYOUT.md).', '',
             'Reference counts exclude generated outputs and historical evidence files. Dynamic imports,',
             'remote archive flattening and working-directory assumptions still need review before a move.', '']
    for group in sorted({row['area'] for row in report['scripts']}):
        lines += ['## '+group, '', '| Script | Purpose | Code references | Documentation references |', '| --- | --- | ---: | ---: |']
        for row in report['scripts']:
            if row['area'] == group:
                name = Path(row['path']).name
                purpose = row['purpose'].replace('|', '\\|') or 'See script and its caller map.'
                lines.append(f"| [{name}]({name}) | {purpose} | {len(row['code_callers'])} | {len(row['documented_references'])} |")
        lines.append('')
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='Write caller-map JSON (refuses to overwrite).')
    parser.add_argument('--index', action='store_true', help='Refresh scripts/README.md.')
    args = parser.parse_args()
    report = inventory()
    if args.output:
        with args.output.open('x') as output:
            json.dump(report, output, indent=2); output.write('\n')
    if args.index:
        (ROOT/'scripts/README.md').write_text(index(report))
    print(json.dumps({'scripts': report['count'], 'code_referenced': sum(bool(r['code_callers']) for r in report['scripts']),
                      'documentation_referenced': sum(bool(r['documented_references']) for r in report['scripts'])}))
